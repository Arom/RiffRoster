const {test,expect} = require('@playwright/test');
const {readFileSync} = require('node:fs');
const axeSource = readFileSync(require.resolve('axe-core',{paths:[require.resolve('lighthouse')]}),'utf8');

async function accessible(page) {
  await page.evaluate(axeSource);
  const violations = await page.evaluate(async () => (await axe.run(document, {runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations.map(item => ({id:item.id,nodes:item.nodes.map(node => node.target)})));
  expect(violations).toEqual([]);
}
test('phase 3 shell, deferred views, keyboard timeline and WCAG checks', async ({page}) => {
  await page.goto('/');
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Page.enable');
  await page.evaluate(() => navigator.serviceWorker.ready);
  const manifest = await cdp.send('Page.getAppManifest');
  expect(manifest.errors).toEqual([]);
  const installability = await cdp.send('Page.getInstallabilityErrors');
  expect(installability.installabilityErrors).toEqual([]);
  await accessible(page);
  await page.locator('#login-name').fill('phase3-accessibility');
  await page.locator('#display-name').fill('Phase Three');
  await page.locator('#account-password').fill('fixture-password-only');
  await page.locator('#access-code').fill('friends-local');
  await page.locator('#login-form button').click();
  await expect(page.locator('#app')).toBeVisible();
  expect(await page.evaluate(() => typeof window.Tesseract)).toBe('undefined');
  expect(await page.evaluate(() => typeof window.RiffRosterShell)).toBe('undefined');
  await page.locator('.pick-button').first().click();
  await expect(page.locator('#my-count')).toHaveText('1');
  await page.locator('.mobile-nav [data-view="mine"]').click();
  await page.context().setOffline(true);
  const downloaded = page.waitForEvent('download');
  await page.locator('[data-action="export-calendar"]').click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toMatch(/\.ics$/);
  const contents = readFileSync(await download.path(),'utf8');
  expect(contents).toContain('BEGIN:VCALENDAR\r\n');
  expect(contents.match(/BEGIN:VEVENT/g)).toHaveLength(1);
  await page.context().setOffline(false);
  await expect(page.locator('#sync-status')).toContainText('All picks synced');
  await page.locator('.mobile-nav [data-view="schedule"]').click();
  await accessible(page);
  const timeline = page.locator('.schedule-timeline');
  await timeline.focus();
  await page.keyboard.press('ArrowRight');
  await expect.poll(() => timeline.evaluate(node => node.scrollLeft)).toBeGreaterThan(0);
  await page.locator('#profile-button').click();
  await expect(page.locator('#profile-modal')).toBeVisible();
  await expect(page.locator('#profile-content')).toContainText('Phase Three');
  await accessible(page);
  await page.keyboard.press('Escape');
  await expect(page.locator('#profile-button')).toBeFocused();
  await page.locator('[data-action="search-events"]').click();
  await page.locator('#event-query').fill('no matching fixture');
  await expect(page.locator('.event-results')).toContainText('No matching');
  await accessible(page);
  await page.locator('#event-query').fill('Brutal');
  await expect(page.locator('.event-results')).toContainText('stages');
  await page.locator('.event-result').first().click();
  await expect(page.locator('#event-search-modal')).not.toBeVisible();
  await page.evaluate(() => { document.documentElement.style.fontSize='200%'; });
  await accessible(page);
  await page.screenshot({path:'test-results/phase3-text-zoom.png',fullPage:false});
  await page.evaluate(() => { document.documentElement.style.fontSize=''; });
  await page.evaluate(() => signOut());
  expect(await page.evaluate(() => RiffRosterWeb.offline.restore('Phase Three'))).toBeNull();
});
