import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const lower = name => name[0].toLowerCase()+name.slice(1);
const contracts = {};
for (const file of ['Accounts','Notifications']) {
  const source = readFileSync(resolve(root,`src/RiffRoster.Domain/${file}/Contracts.cs`),'utf8');
  for (const match of source.matchAll(/public sealed record (\w+)\(([^;]*?)\);/gs)) {
    if (!match[1].endsWith('Request') && match[1] !== 'BrowserPushKeys') continue;
    const fields = match[2].split(',').map(field => {
      const [,type,name] = field.trim().match(/^([\w<>?]+)\s+(\w+)$/) ?? [];
      if (!type || !name) throw new Error(`Unsupported contract field in ${match[1]}`);
      return {name:lower(name),type};
    });
    contracts[match[1]] = fields;
  }
}
function typeOf(type) {
  if (type.endsWith('?')) return `${typeOf(type.slice(0,-1))} | null`;
  if (type.startsWith('List<')) return `${typeOf(type.slice(5,-1))}[]`;
  if (['string','DateOnly','DateTimeOffset'].includes(type)) return 'string';
  if (type === 'bool') return 'boolean';
  if (type === 'int') return 'number';
  if (contracts[type]) return type;
  throw new Error(`Unsupported contract type ${type}`);
}
const routes = [];
for (const file of readdirSync(resolve(root,'src/RiffRoster.Api/Endpoints')).filter(file => file.endsWith('.cs')).sort()) {
  const source = readFileSync(resolve(root,'src/RiffRoster.Api/Endpoints',file),'utf8');
  for (const match of source.matchAll(/api\.Map(Get|Post|Put|Delete)\("([^"]+)",\s*(?:async\s*)?\(([^)]*)\)\s*=>/g)) {
    const path = '/api'+match[2];
    const params = [...path.matchAll(/\{(\w+)\}/g)].map(match => match[1]);
    const body = match[3].match(/(\w+Request)\s+request/)?.[1];
    routes.push({method:match[1].toUpperCase(),path,params,body});
  }
}
const output = resolve(root,'src/RiffRoster.Web/src/app/generated');mkdirSync(output,{recursive:true});
const lines = ['// Generated by tools/generate-api-client.mjs. Do not edit.',"import { requestJson } from '../api';"];
for (const [name,fields] of Object.entries(contracts)) lines.push(`export interface ${name} { ${fields.map(field => `${field.name}: ${typeOf(field.type)}`).join('; ')} }`);
lines.push('export const generatedApi = {');
for (const route of routes) {
  const name = route.method.toLowerCase()+route.path.slice(4).split(/[\/{}-]/).filter(Boolean).map(part => part[0].toUpperCase()+part.slice(1)).join('');
  const args = [...route.params.map(name => `${name}: string`), ...(route.body ? [`body: ${route.body}`] : [])];
  const url = route.path.replace(/\{(\w+)\}/g, (_,name) => '${encodeURIComponent('+name+')}');
  lines.push(`  ${name}: (${args.join(', ')}) => requestJson(\`${url}\`, {method:'${route.method}'${route.body ? ', body:JSON.stringify(body)' : ''}}),`);
}
lines.push('};','');
writeFileSync(resolve(output,'client.ts'),lines.join('\n'));
console.log(`Generated ${Object.keys(contracts).length} request contracts and ${routes.length} endpoint methods.`);

function schema(type) {
  if (type.endsWith('?')) return {...schema(type.slice(0,-1)),nullable:true};
  if (type.startsWith('List<')) return {type:'array',items:schema(type.slice(5,-1))};
  if (type === 'bool') return {type:'boolean'};
  if (type === 'int') return {type:'integer',format:'int32'};
  if (type === 'string') return {type:'string'};
  if (type === 'DateOnly') return {type:'string',format:'date'};
  if (type === 'DateTimeOffset') return {type:'string',format:'date-time'};
  return {$ref:'#/components/schemas/'+type};
}
const schemas = Object.fromEntries(Object.entries(contracts).map(([name,fields]) => [name,{type:'object',properties:Object.fromEntries(fields.map(field => [field.name,schema(field.type)])),required:fields.filter(field => !field.type.endsWith('?')).map(field => field.name)}]));
const paths = {};
for (const route of routes) {
  paths[route.path] ??= {};
  paths[route.path][route.method.toLowerCase()] = {
    parameters:route.params.map(name => ({name,in:'path',required:true,schema:{type:'string'}})),
    ...(route.body ? {requestBody:{required:true,content:{'application/json':{schema:{$ref:'#/components/schemas/'+route.body}}}}} : {}),
    responses:{default:{description:'Endpoint response; runtime client decoders validate successful response shapes.'}}
  };
}
mkdirSync(resolve(root,'docs'),{recursive:true});
writeFileSync(resolve(root,'docs/api-contracts.openapi.json'),JSON.stringify({openapi:'3.0.3',info:{title:'RiffRoster current request contracts',version:'1.0.0'},paths,components:{schemas}},null,2)+'\n');
